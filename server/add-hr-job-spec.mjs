import { withLocalConnection } from './db.mjs';

await withLocalConnection(async (connection) => {
  try {
    await connection.execute(`CREATE TABLE bes_hr_job_spec (
      job_spec_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      position_id NUMBER NOT NULL REFERENCES bes_positions(position_id) ON DELETE CASCADE,
      position_level NUMBER DEFAULT 4 NOT NULL,
      specification VARCHAR2(180) NOT NULL,
      description VARCHAR2(2000),
      sort_order NUMBER DEFAULT 0 NOT NULL,
      is_active CHAR(1) DEFAULT 'Y' NOT NULL,
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT chk_bes_hr_job_spec_level CHECK (position_level BETWEEN 1 AND 5),
      CONSTRAINT chk_bes_hr_job_spec_active CHECK (is_active IN ('Y','N'))
    )`);
  } catch (error) { if (error.errorNum !== 955) throw error; }
  try { await connection.execute(`CREATE INDEX ix_bes_hr_job_spec_position ON bes_hr_job_spec (position_id, position_level, is_active)`); }
  catch (error) { if (error.errorNum !== 955) throw error; }
  const result = await connection.execute(`SELECT column_name,data_type,data_length,nullable,data_default FROM user_tab_columns WHERE table_name='BES_HR_JOB_SPEC' ORDER BY column_id`);
  console.log(JSON.stringify(result.rows, null, 2));
});
