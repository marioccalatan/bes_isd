export const TRAINING_CATEGORY_NAMES = [
  'Mandatory, Regulatory & Compliance',
  'Technical & Functional Competency',
  'Safety, Health & Emergency Preparedness',
  'Leadership & Management Development',
  'Behavioral & Interpersonal Effectiveness',
  'Customer Service & Stakeholder Relations',
  'Digital, Data & Emerging Technology',
  'Professional & Career Development',
  'Academic & Advanced Development',
  'Organizational & Strategic Capability',
];

export async function initializeTrainingCategories(connection) {
  async function create(sql) {
    try { await connection.execute(sql); } catch (error) { if (error.errorNum !== 955) throw error; }
  }
  await create(`CREATE TABLE BES_TRAINING_CATEGORIES (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(300) NOT NULL UNIQUE
  )`);
  await create(`CREATE TABLE BES_TRAIN_CATEGORY_BACKUP (
    TRAINING_ID NUMBER PRIMARY KEY, ORIGINAL_CATEGORY VARCHAR2(2000),
    MIGRATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
  )`);
  await create(`CREATE TABLE BES_TRAIN_CATEGORY_SETUP (ID NUMBER PRIMARY KEY)`);
  const seeded = (await connection.execute('SELECT ID FROM BES_TRAIN_CATEGORY_SETUP WHERE ID=1')).rows.length;
  if (!seeded) for (const name of TRAINING_CATEGORY_NAMES) {
    await connection.execute(`INSERT INTO BES_TRAINING_CATEGORIES (NAME)
      SELECT :name FROM dual WHERE NOT EXISTS (SELECT 1 FROM BES_TRAINING_CATEGORIES WHERE NAME=:name)`, { name });
  }
  if (!seeded) await connection.execute('INSERT INTO BES_TRAIN_CATEGORY_SETUP (ID) VALUES (1)');
  const lookup = (await connection.execute('SELECT ID, NAME FROM BES_TRAINING_CATEGORIES')).rows;
  const records = (await connection.execute("SELECT ID, TS_CATEGORY FROM TRAINING_SEMINAR WHERE TS_CATEGORY IS NOT NULL AND LTRIM(TS_CATEGORY) LIKE '[%' FOR UPDATE")).rows;
  // Validate all legacy selections before changing any training record.
  const changes = records.map((row) => {
    const names = JSON.parse(row.TS_CATEGORY);
    if (!Array.isArray(names) || names.some((name) => !lookup.some((category) => category.NAME === name))) {
      throw new Error(`Cannot migrate training categories for record ${row.ID}: unknown category.`);
    }
    return { id: row.ID, original: row.TS_CATEGORY,
      ids: lookup.filter((category) => names.includes(category.NAME)).sort((a, b) => a.ID - b.ID).map((category) => category.ID).join(', ') || null };
  });
  for (const row of changes) {
    await connection.execute(`INSERT INTO BES_TRAIN_CATEGORY_BACKUP (TRAINING_ID, ORIGINAL_CATEGORY)
      SELECT :id, :original FROM dual WHERE NOT EXISTS (SELECT 1 FROM BES_TRAIN_CATEGORY_BACKUP WHERE TRAINING_ID=:id)`, { id: row.id, original: row.original });
    await connection.execute('UPDATE TRAINING_SEMINAR SET TS_CATEGORY=:ids WHERE ID=:id', { id: row.id, ids: row.ids });
  }
  await connection.commit();
}
